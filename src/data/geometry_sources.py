"""Sources of base geometries (skull + paired face) for the dataset builder.

  ProceduralSource  the stylised procedural skull/face generator (``generator.py``); fast, fully synthetic,
                    used for tests and as a controlled toy world.
  Mug500Source      REAL CT-derived skulls (MUG500+, CC BY 4.0, prepared by ``scripts/prepare_mug500.py``) with a
                    SYNTHETIC soft-tissue face draped over each skull (``face_from_skull.py``).

Both return a ``BaseGeometry`` in the skull's own millimetres. In every case the FACE is synthetic; only the
Mug500 skulls are real, anonymised patient-derived geometry (never redistributed from this repository).
"""
from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

import numpy as np

from . import face_from_skull as ffs
from . import generator as gen
from . import real_skulls as rs

PROCEDURAL_PROVENANCE = ("SYNTHETIC: procedurally generated by src/data/generator.py. Not real human anatomy, "
                         "not forensic data, no participants. Soft-tissue values are assumed, not measured.")
MUG500_PROVENANCE = ("MIXED: the SKULL is real anonymised CT-derived geometry from MUG500+ (Li et al. 2021, CC BY 4.0, "
                     "DOI 10.6084/m9.figshare.9616319). The FACE is SYNTHETIC: a procedurally generated soft-tissue layer "
                     "with assumed thickness values, not measured facial data. No forensic or identification validity.")
FACE_KEYS = ("thickness_scale", "thickness_field_amp", "nose_projection", "lip_fullness", "cheek_fat",
             "unobserved_field_amp", "thickness_field_seed", "unobserved_field_seed")


@dataclass
class BaseGeometry:
    base_id: int
    skull_verts: np.ndarray
    skull_faces: np.ndarray
    region: np.ndarray
    face_base: np.ndarray          # (Vf,3) bone-side start of each face vertex (skull surface / envelope)
    face_verts: np.ndarray         # (Vf,3) ground-truth face, vertex-wise corresponding across subjects
    face_faces: np.ndarray
    thickness: np.ndarray          # (Vf,) mm
    params: dict
    real_skull: bool
    provenance: str
    face_grid_xz: np.ndarray | None = None   # (Vf,2) reference-frame grid coordinates (grid-based faces only)
    extra: dict = field(default_factory=dict)


def skull_rms(a: np.ndarray, flat_others: np.ndarray, n_verts: int) -> np.ndarray:
    """Per-vertex RMS 3D distance (mm) between flattened skull ``a`` and each row of ``flat_others``."""
    return np.sqrt(((flat_others - a) ** 2).sum(1) / n_verts)


def generate_distinct_base(b: int, seed: int, gcfg: dict, subdivisions: int, accepted: list[np.ndarray]):
    """Procedural base ``b``, redrawn (``attempt`` 0,1,2,...) until its skull is >= ``min_pairwise_skull_rms_mm``
    from every accepted skull. Appends the accepted skull to ``accepted``; returns ``(subject, attempt)``."""
    thr, max_attempts = float(gcfg["min_pairwise_skull_rms_mm"]), int(gcfg["max_attempts"])
    for attempt in range(max_attempts):
        sub = gen.generate_base(b, seed, gcfg, subdivisions, attempt)
        flat = sub.skull_verts.reshape(-1)
        if not accepted or skull_rms(flat, np.stack(accepted), len(sub.skull_verts)).min() >= thr:
            accepted.append(flat)
            return sub, attempt
    raise RuntimeError(f"base {b}: no candidate >= {thr} mm from existing skulls in {max_attempts} attempts")


class ProceduralSource:
    name = "procedural"
    real_skull = False

    def __init__(self, cfg: dict):
        self.cfg, self.seed = cfg, int(cfg["dataset"]["seed"])
        self.gcfg, self.sub_div = cfg["generator"], int(cfg["mesh"]["cranium_subdivisions"])
        self.accepted: list[np.ndarray] = []
        self.attempts: dict[int, int] = {}

    def available(self) -> int | None:
        return None

    def get(self, b: int) -> BaseGeometry:
        sub, attempt = generate_distinct_base(b, self.seed, self.gcfg, self.sub_div, self.accepted)
        self.attempts[b] = attempt
        return BaseGeometry(b, sub.skull_verts, sub.skull_faces, sub.region, sub.skull_verts[sub.face_vert_index],
                            sub.face_verts, sub.face_faces, sub.thickness, sub.params, False, PROCEDURAL_PROVENANCE,
                            extra=dict(generation_attempt=attempt))

    def summary(self) -> dict:
        return dict(near_duplicate_rejection=dict(
            threshold_rms_mm=self.gcfg["min_pairwise_skull_rms_mm"], candidates_rejected=int(sum(self.attempts.values())),
            bases_needing_redraw=int(sum(a > 0 for a in self.attempts.values()))))


class Mug500Source:
    name = "mug500"
    real_skull = True

    def __init__(self, cfg: dict):
        self.cfg, self.seed = cfg, int(cfg["dataset"]["seed"])
        m = cfg["mug500"]
        self.dir = Path(m["processed_dir"])
        self.cases = sorted(p for p in self.dir.glob("A[0-9][0-9][0-9][0-9].npz"))
        if m.get("max_cases"):
            self.cases = self.cases[: int(m["max_cases"])]
        if not self.cases:
            raise FileNotFoundError(f"no prepared skulls in {self.dir}; run scripts/fetch_mug500.py and scripts/prepare_mug500.py")
        self.gcfg = cfg["generator"]

    def available(self) -> int:
        return len(self.cases)

    def get(self, b: int) -> BaseGeometry:
        d = np.load(self.cases[b])
        v, f, s = d["verts"].astype(np.float64), d["faces"].astype(np.int64), float(d["scale"])
        rng = np.random.default_rng(np.random.SeedSequence([self.seed, b, 91]))
        p = {k: v_ for k, v_ in gen.sample_params(rng, self.gcfg).items() if k in FACE_KEYS}
        ref = s * v
        out = ffs.build_face(ref, p, self.gcfg["min_thickness_mm"])
        X, Z = np.meshgrid(ffs.FACE_X, ffs.FACE_Z, indexing="xy")
        grid_xz = np.stack([X[out["mask"]], Z[out["mask"]]], 1)
        return BaseGeometry(b, v.astype(np.float32), f, rs.region_labels(ref), out["base"] / s, out["face"] / s, out["faces"],
                            out["thickness"] / s, p, True, MUG500_PROVENANCE, grid_xz,
                            extra=dict(case=self.cases[b].stem, scale=s, align_rms_mm=float(d["align_rms_mm"])))

    def summary(self) -> dict:
        src = self.dir.parent / "SOURCE.json"
        import json
        return dict(skull_source=json.loads(src.read_text()) if src.exists() else {}, n_cases=len(self.cases))


def make_source(cfg: dict, name: str | None = None):
    name = name or cfg["dataset"].get("source", "procedural")
    if name == "procedural":
        return ProceduralSource(cfg)
    if name == "mug500":
        return Mug500Source(cfg)
    raise ValueError(f"unknown geometry source {name!r}")
